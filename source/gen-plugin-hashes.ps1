
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
& (Join-Path $root 'build-preview.ps1')
$files = @('7zip\7z.exe', '7zip\7z.dll', '7zip\7z.sfx', 'network\FileCompassNetwork.dll', 'everything\Everything64.dll', 'cloud\rclone.exe')
$files += 'smart\smartctl.exe'
$files += Get-ChildItem -LiteralPath (Join-Path $root 'plugins\media') -File | Where-Object { $_.Extension -in '.exe','.dll' } | ForEach-Object { 'media\' + $_.Name }
$sshfs = Join-Path $root 'plugins\sshfs\bin'
if (Test-Path -LiteralPath $sshfs) { $files += Get-ChildItem -LiteralPath $sshfs -File | Where-Object { $_.Extension -in '.exe','.dll' } | ForEach-Object { 'sshfs\bin\' + $_.Name } }
$lines = foreach ($relative in $files) {
    $path = Join-Path (Join-Path $root 'plugins') $relative
    if (-not (Test-Path -LiteralPath $path)) { throw "Chybí plugin: $path" }
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    '            { "' + $relative.Replace('\', '\\') + '", "' + $hash + '" },'
}
$lines += foreach ($folder in @('ui','preview')) {
    foreach ($file in Get-ChildItem -LiteralPath (Join-Path $root $folder) -File | Where-Object { $_.Extension -eq '.dll' }) {
        $resourceFolder = if ($folder -eq 'ui') { 'libraries' } else { 'preview' }
        $relative = $resourceFolder + '\' + $file.Name
        '            { "' + $relative.Replace('\', '\\') + '", "' + (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant() + '" },'
    }
}
$previewLibrary = Join-Path $root 'obj\preview\preview.dll'
$lines += '            { "preview\\preview.dll", "' + (Get-FileHash -LiteralPath $previewLibrary -Algorithm SHA256).Hash.ToLowerInvariant() + '" },'
$code = @(
    '// <auto-generated> gen-plugin-hashes.ps1 - do not edit manually. </auto-generated>',
    'using System.Collections.Generic;',
    'namespace FileCompass',
    '{',
    '    internal static class PluginHashes',
    '    {',
    '        internal static readonly Dictionary<string, string> Expected = new Dictionary<string, string>(System.StringComparer.OrdinalIgnoreCase)',
    '        {'
) + $lines + @('        };', '    }', '}')
$target = Join-Path $root 'src\PluginHashes.cs'
$text = ($code -join "`r`n") + "`r`n"
if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target) -ne $text) {
    [IO.File]::WriteAllText($target, $text, (New-Object Text.UTF8Encoding($true)))
}
