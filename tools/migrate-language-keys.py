"""One-time semantic-key migration. The saved mapping makes it reviewable/idempotent."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'source/languages/cs.lng'
MAPPING = ROOT / 'tools/language-key-migration.json'
REPORT = ROOT / 'reports/language-key-migration'

def render(catalog):
    lines = ['{', '  "_language": ' + json.dumps(catalog['_language'], ensure_ascii=False) + ',',
             '  "_name": ' + json.dumps(catalog['_name'], ensure_ascii=False) + ',']
    previous = None
    items = sorted((k, v) for k, v in catalog.items() if not k.startswith('_'))
    for index, (key, value) in enumerate(items):
        group = key.split('.')[0]
        if group != previous:
            lines.append('')
        lines.append('  ' + json.dumps(key) + ': ' + json.dumps(value, ensure_ascii=False) + (',' if index + 1 < len(items) else ''))
        previous = group
    lines.append('}')
    return '\n'.join(lines) + '\n'

def main():
    original = json.loads(CATALOG.read_text(encoding='utf-8-sig'))
    if not MAPPING.exists():
        names = (ROOT / 'tools/language-semantic-names.txt').read_text().split()
        keys = [key for key in original if not key.startswith('_')]
        assert len(names) == len(keys) and len(set(names)) == len(names)
        assert all(re.fullmatch(r'[a-z][A-Za-z0-9]*(?:\.[a-z][A-Za-z0-9]*)+', name) for name in names)
        mapping = dict(zip(keys, names))
        REPORT.mkdir(parents=True, exist_ok=True)
        (REPORT / 'original-cs.lng').write_text(CATALOG.read_text(encoding='utf-8-sig'), encoding='utf-8')
        MAPPING.write_text(json.dumps(mapping, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    mapping = json.loads(MAPPING.read_text(encoding='utf-8'))
    for path in (ROOT / 'source/src').glob('*.cs'):
        if path.name == 'LanguageKeyAliases.cs':
            continue
        source = path.read_text(encoding='utf-8-sig')
        changed = re.sub(r'"([A-Za-z0-9_.]+)"', lambda match: json.dumps(mapping.get(match[1], match[1])), source)
        if source != changed:
            path.write_text(changed, encoding='utf-8')
    migrated = {mapping.get(key, key): value for key, value in original.items()}
    assert len(migrated) == len(original)
    CATALOG.write_text(render(migrated), encoding='utf-8')
    aliases = [(old, new) for old, new in mapping.items() if old != new]
    code = '''// Compatibility with language packs using the original generated IDs.
// Generated by tools/migrate-language-keys.py; new code uses semantic keys.
using System.Collections.Generic;
namespace CommanderCZ
{
    internal static class LanguageKeyAliases
    {
        static readonly Dictionary<string, string> names = new Dictionary<string, string>
        {
'''
    code += ''.join('            { ' + json.dumps(old) + ', ' + json.dumps(new) + ' },\n' for old, new in aliases)
    code += '''        };
        internal static string Resolve(string key) { string name; return names.TryGetValue(key, out name) ? name : key; }
        internal static Dictionary<string, string> Normalize(Dictionary<string, string> values)
        {
            var result = new Dictionary<string, string>(values);
            foreach (var pair in values) {
                string name = Resolve(pair.Key);
                if (name == pair.Key) continue;
                if (!values.ContainsKey(name)) result[name] = pair.Value;
                result.Remove(pair.Key);
            }
            return result;
        }
    }
}
'''
    (ROOT / 'source/src/LanguageKeyAliases.cs').write_text(code, encoding='utf-8')
    before = json.loads((REPORT / 'original-cs.lng').read_text(encoding='utf-8'))
    assert all(migrated[mapping.get(key, key)] == value for key, value in before.items())
    assert not any(re.fullmatch(r'text\.[0-9a-f]{16}', key) for key in migrated)
    print(f'{len(migrated) - 2} semantic keys; all original values preserved; {len(aliases)} legacy aliases')

if __name__ == '__main__':
    main()
